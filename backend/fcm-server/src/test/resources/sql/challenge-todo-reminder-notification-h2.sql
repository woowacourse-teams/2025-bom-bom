-- 엔티티의 TINYINT(1) columnDefinition을 H2가 해석하지 못해 자동 DDL이 실패하므로 테스트용으로 직접 생성한다.
CREATE TABLE IF NOT EXISTS challenge_todo_reminder_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    attempts INT DEFAULT 0 NOT NULL,
    next_retry_at TIMESTAMP(6),
    last_error VARCHAR(1024),
    challenge_id BIGINT NOT NULL,
    challenge_name VARCHAR(255) NOT NULL,
    phase VARCHAR(32) NOT NULL,
    streak INT DEFAULT 0 NOT NULL,
    days_since_last_participation INT,
    remaining_absences INT DEFAULT 0 NOT NULL,
    is_last_day BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);
